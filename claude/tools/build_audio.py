#!/usr/bin/env python3
"""Build audio assets + embedded JS data files for a unit from spec/content.json or spec/uN.json.

Usage:
  python3 tools/build_audio.py u0
  python3 tools/build_audio.py u1
  python3 tools/build_audio.py u2

Generates:
  audio/<hash>.mp3                  (mp3 files, deduped by text+voice)
  data/audio-manifest.js            (merged across all runs: "voice|text" -> "audio/<hash>.mp3")
  data/<unit>-data.js               (window.UNIT_DATA.<unit> = {...raw json...})
"""
import sys, os, json, asyncio, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from audio_get import ensure  # noqa: E402

AUDIO_DIR = os.path.join(ROOT, "audio")
DATA_DIR = os.path.join(ROOT, "data")
MANIFEST_JS = os.path.join(DATA_DIR, "audio-manifest.js")


def parse_keys(keys):
    """Return list of (voice, text) following the content.json key convention:
    plain -> es, 'en:x' -> en, 'ex:x' -> es (spanish example word)."""
    out = []
    for k in keys:
        if k.startswith("en:"):
            out.append(("en", k[3:]))
        elif k.startswith("ex:"):
            out.append(("es", k[3:]))
        else:
            out.append(("es", k))
    return out


def collect_pairs_from_unit(u):
    pairs = set()
    for _gname, cards in u.get("G", []):
        for c in cards:
            for pair in parse_keys(c.get("keys", [])):
                pairs.add(pair)
    for q in u.get("Q", []):
        if q.get("say"):
            pairs.add(("es", q["say"]))
    for item in u.get("D", []):
        for pair in parse_keys(item.get("keys", [])):
            pairs.add(pair)
    return pairs


def collect_pairs_from_wordlist(u):
    """u1/u2 style: {"W": [[article, word, zh], ...], "S": [[es, zh], ...]}"""
    pairs = set()
    for row in u.get("W", []):
        article, word = row[0], row[1]
        pairs.add(("es", f"{article} {word}"))
        pairs.add(("es", word))
    for row in u.get("S", []):
        pairs.add(("es", row[0]))
    return pairs


def load_manifest():
    if os.path.exists(MANIFEST_JS):
        with open(MANIFEST_JS, encoding="utf-8") as f:
            txt = f.read()
        start = txt.index("{")
        end = txt.rindex("}")
        return json.loads(txt[start : end + 1])
    return {}


def save_manifest(manifest):
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(MANIFEST_JS, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/build_audio.py -- do not edit by hand\n")
        f.write("window.AUDIO_MANIFEST = ")
        json.dump(manifest, f, ensure_ascii=False, indent=1)
        f.write(";\n")


async def build(unit_key, unit_json, is_wordlist):
    os.makedirs(AUDIO_DIR, exist_ok=True)
    manifest = load_manifest()
    pairs = collect_pairs_from_wordlist(unit_json) if is_wordlist else collect_pairs_from_unit(unit_json)
    print(f"[{unit_key}] {len(pairs)} unique (voice,text) pairs")
    done = 0
    for voice, text in sorted(pairs):
        mkey = f"{voice}|{text}"
        if mkey in manifest and os.path.exists(os.path.join(ROOT, manifest[mkey])):
            continue
        h = hashlib.md5(mkey.encode("utf-8")).hexdigest()[:16]
        fname = f"{voice}_{h}.mp3"
        dest = os.path.join(AUDIO_DIR, fname)
        await ensure(text, voice, dest)
        manifest[mkey] = f"audio/{fname}"
        done += 1
        if done % 10 == 0:
            print(f"  ...{done} generated")
    save_manifest(manifest)
    print(f"[{unit_key}] generated/verified {len(pairs)} clips, {done} newly synthesized")

    os.makedirs(DATA_DIR, exist_ok=True)
    out_path = os.path.join(DATA_DIR, f"{unit_key}-data.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"// AUTO-GENERATED by tools/build_audio.py from spec -- do not edit by hand\n")
        f.write("window.UNIT_DATA = window.UNIT_DATA || {};\n")
        f.write(f"window.UNIT_DATA.{unit_key} = ")
        json.dump(unit_json, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(f"[{unit_key}] wrote {out_path}")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    unit_key = sys.argv[1]
    content_path = os.path.join(ROOT, "spec", "content.json")
    unit_path = os.path.join(ROOT, "spec", f"{unit_key}.json")
    if os.path.exists(unit_path):
        with open(unit_path, encoding="utf-8") as f:
            unit_json = json.load(f)
        is_wordlist = "W" in unit_json
    else:
        with open(content_path, encoding="utf-8") as f:
            content = json.load(f)
        unit_json = content[unit_key]
        is_wordlist = False
    asyncio.run(build(unit_key, unit_json, is_wordlist))


if __name__ == "__main__":
    main()
